/**
 * EOS Project Compiler.
 *
 * Compiles the Project IR (dataset.ts) into deterministic artifacts:
 *   - eos/tspecs/<id>.yaml           one fully-specified TSPEC per unit
 *   - eos/state/project.*.{yaml,json} machine-readable project state
 *
 * It first VALIDATES the dataset (the Project IR validator) and fails non-zero on any
 * error, so CI can gate on it. No production code is generated — only EOS artifacts.
 *
 * Run: pnpm eos:compile   (tsx eos/compiler/compile.ts)
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { DATASET } from "./dataset.js";
import { EOS, Role, State, type Tspec, type TspecSource } from "./types.js";
import { HAPPY_PATH } from "./state-machine.js";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "..", "..");
const TSPEC_DIR = resolve(ROOT, "eos", "tspecs");
const STATE_DIR = resolve(ROOT, "eos", "state");
const COMPLETED_FILE = resolve(ROOT, "eos", "completed.json");

/** TSPEC ids merged/done on main (eos/completed.json). Synced on every merge. */
function loadCompleted(): Set<string> {
  if (!existsSync(COMPLETED_FILE)) return new Set();
  const parsed = JSON.parse(readFileSync(COMPLETED_FILE, "utf8")) as { completed?: string[] };
  return new Set(parsed.completed ?? []);
}

// --- minimal deterministic YAML emitter ------------------------------------
function yamlScalar(v: unknown): string {
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  const s = String(v);
  return `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}
function toYaml(value: unknown, indent = 0): string {
  const pad = "  ".repeat(indent);
  if (Array.isArray(value)) {
    if (value.length === 0) return "[]";
    return "\n" + value.map((item) => {
      if (item !== null && typeof item === "object") {
        // Render object entries at indent+1; the first entry sits on the dash line
        // so subsequent keys align under it (valid block-sequence-of-mappings YAML).
        const childPad = "  ".repeat(indent + 1);
        const lines = Object.entries(item as Record<string, unknown>).map(([k, v]) => {
          const rendered = toYaml(v, indent + 2);
          const inline = !rendered.startsWith("\n");
          return `${childPad}${k}:${inline ? " " + rendered : rendered}`;
        });
        lines[0] = `${pad}- ${lines[0]!.slice(childPad.length)}`;
        return lines.join("\n");
      }
      return `${pad}- ${yamlScalar(item)}`;
    }).join("\n");
  }
  if (value !== null && typeof value === "object") {
    const entries = Object.entries(value as Record<string, unknown>);
    if (entries.length === 0) return "{}";
    return "\n" + entries.map(([k, v]) => {
      const rendered = toYaml(v, indent + 1);
      const inline = !rendered.startsWith("\n");
      return `${pad}${k}:${inline ? " " + rendered : rendered}`;
    }).join("\n");
  }
  return yamlScalar(value);
}
function writeYaml(file: string, header: string, doc: Record<string, unknown>): void {
  const body = toYaml(doc).replace(/^\n/, "");
  writeFileSync(file, `# ${header}\n# GENERATED by eos/compiler/compile.ts — do not edit by hand.\n${body}\n`, "utf8");
}

// --- helpers ---------------------------------------------------------------
function slug(s: string): string {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
}
function repositoryPath(s: TspecSource): string {
  if (s.package === "ci") return ".github";
  if (s.package === "scripts") return `scripts/${s.module}`;
  if (s.package === "fixtures") return `fixtures/${s.module}`;
  if (["cli", "compiler-api", "worker"].includes(s.package)) return `apps/${s.package}`;
  return `packages/${s.package}`;
}

// --- validation + graph computations ---------------------------------------
interface Compiled {
  readonly tspecs: Tspec[];
  readonly order: string[];
  readonly errors: string[];
  readonly warnings: string[];
}

function compile(dataset: readonly TspecSource[]): Compiled {
  const errors: string[] = [];
  const warnings: string[] = [];
  const byId = new Map<string, TspecSource>();

  // Unique ids + single owner + role validity.
  for (const t of dataset) {
    if (byId.has(t.id)) errors.push(`duplicate TSPEC id: ${t.id}`);
    byId.set(t.id, t);
    if (t.owner !== Role.Architect && t.owner !== Role.Implementer) errors.push(`${t.id}: invalid owner ${t.owner}`);
  }

  // Dependency existence + self-dependency.
  for (const t of dataset) {
    for (const dep of t.depends_on) {
      if (dep === t.id) errors.push(`${t.id}: depends on itself`);
      if (!byId.has(dep)) errors.push(`${t.id}: depends on unknown ${dep}`);
    }
  }

  // Cycle detection + topological order (Kahn).
  const indeg = new Map<string, number>();
  const adj = new Map<string, string[]>();
  for (const t of dataset) {
    indeg.set(t.id, 0);
    adj.set(t.id, []);
  }
  for (const t of dataset) {
    for (const dep of t.depends_on) {
      if (!byId.has(dep)) continue;
      adj.get(dep)!.push(t.id);
      indeg.set(t.id, (indeg.get(t.id) ?? 0) + 1);
    }
  }
  const queue = [...dataset].filter((t) => (indeg.get(t.id) ?? 0) === 0).map((t) => t.id).sort();
  const order: string[] = [];
  while (queue.length) {
    const id = queue.shift()!;
    order.push(id);
    for (const next of [...adj.get(id)!].sort()) {
      indeg.set(next, indeg.get(next)! - 1);
      if (indeg.get(next) === 0) queue.push(next);
    }
  }
  if (order.length !== dataset.length) errors.push("dependency cycle detected (impossible execution order)");

  // Orphans: implementer TSPECs with no path from an architect contract are suspect.
  const hasDependents = new Set<string>();
  for (const t of dataset) for (const d of t.depends_on) hasDependents.add(d);
  for (const t of dataset) {
    if (t.owner === Role.Implementer && t.depends_on.length === 0) {
      warnings.push(`${t.id}: implementer TSPEC with no dependencies (verify it is truly foundational)`);
    }
  }

  // Wave = longest dependency depth; critical path = longest effort path.
  const wave = new Map<string, number>();
  const pathEffort = new Map<string, number>();
  const predOnPath = new Map<string, string | null>();
  for (const id of order) {
    const t = byId.get(id)!;
    let w = 0;
    let bestEffort = 0;
    let bestPred: string | null = null;
    for (const dep of t.depends_on) {
      if (!byId.has(dep)) continue;
      w = Math.max(w, (wave.get(dep) ?? 0) + 1);
      const e = pathEffort.get(dep) ?? 0;
      if (e > bestEffort) {
        bestEffort = e;
        bestPred = dep;
      }
    }
    wave.set(id, w);
    pathEffort.set(id, bestEffort + t.estimated_effort);
    predOnPath.set(id, bestPred);
  }

  // Reconstruct the critical path (max finishing effort).
  const criticalSet = new Set<string>();
  if (order.length) {
    let tail = order[0]!;
    for (const id of order) if ((pathEffort.get(id) ?? 0) > (pathEffort.get(tail) ?? 0)) tail = id;
    let cur: string | null = tail;
    while (cur) {
      criticalSet.add(cur);
      cur = predOnPath.get(cur) ?? null;
    }
  }

  // Derive full TSPECs.
  const completed = loadCompleted();
  const tspecs: Tspec[] = dataset.map((s) => {
    const w = wave.get(s.id) ?? 0;
    const spec_path = `eos/specs/${s.id}.spec.md`;
    const spec_required = s.owner === Role.Implementer;
    const spec_status: Tspec["spec_status"] = existsSync(resolve(ROOT, spec_path)) ? "WRITTEN" : "MISSING";
    return {
      ...s,
      state: completed.has(s.id) ? State.Complete : State.Draft,
      repository_path: repositoryPath(s),
      branch: `feature/${s.id.toLowerCase()}-${slug(s.title)}`,
      parent_branch: EOS.parentBranch,
      blocks: [...(adj.get(s.id) ?? [])].sort(),
      reviewers: [Role.Architect],
      version: EOS.version,
      created_at: EOS.createdAt,
      updated_at: EOS.updatedAt,
      wave: w,
      critical_path: criticalSet.has(s.id),
      parallel_group: `wave-${w}`,
      spec_path,
      spec_required,
      spec_status,
    };
  }).sort((a, b) => a.wave - b.wave || a.id.localeCompare(b.id));

  return { tspecs, order, errors, warnings };
}

// --- emit state artifacts --------------------------------------------------
function emit(c: Compiled): void {
  rmSync(TSPEC_DIR, { recursive: true, force: true });
  mkdirSync(TSPEC_DIR, { recursive: true });
  mkdirSync(STATE_DIR, { recursive: true });

  // Per-TSPEC YAML in canonical field order.
  const FIELDS: (keyof Tspec)[] = [
    "id", "title", "owner", "state", "package", "module", "repository_path", "branch", "parent_branch",
    "priority", "complexity", "risk", "estimated_effort", "depends_on", "blocks", "references",
    "architecture_documents", "deliverables", "outputs", "tests", "reviewers", "acceptance_criteria",
    "forbidden_changes", "labels", "version", "created_at", "updated_at", "wave", "critical_path", "parallel_group",
    "spec_path", "spec_required", "spec_status",
  ];
  for (const t of c.tspecs) {
    const ordered: Record<string, unknown> = {};
    for (const f of FIELDS) ordered[f] = t[f];
    writeYaml(resolve(TSPEC_DIR, `${t.id}.yaml`), `TSPEC ${t.id} — ${t.title}`, ordered);
  }

  const waves = [...new Set(c.tspecs.map((t) => t.wave))].sort((a, b) => a - b);
  const byWave = (w: number) => c.tspecs.filter((t) => t.wave === w);
  const architects = c.tspecs.filter((t) => t.owner === Role.Architect);
  const implementers = c.tspecs.filter((t) => t.owner === Role.Implementer);
  const totalEffort = c.tspecs.reduce((s, t) => s + t.estimated_effort, 0);
  const criticalIds = c.tspecs.filter((t) => t.critical_path).map((t) => t.id);
  const specRequired = c.tspecs.filter((t) => t.spec_required);
  const specWritten = specRequired.filter((t) => t.spec_status === "WRITTEN");
  const specCoveragePct = specRequired.length
    ? Number(((specWritten.length / specRequired.length) * 100).toFixed(1))
    : 100;

  // Completion + readiness, computed from synced state (eos/completed.json).
  const completeSet = new Set(c.tspecs.filter((t) => t.state === State.Complete).map((t) => t.id));
  const ready = c.tspecs.filter(
    (t) =>
      !completeSet.has(t.id) &&
      t.spec_required &&
      t.spec_status === "WRITTEN" &&
      t.depends_on.every((d) => completeSet.has(d)),
  );
  const blocked = c.tspecs.filter(
    (t) => !completeSet.has(t.id) && t.spec_required && !t.depends_on.every((d) => completeSet.has(d)),
  );

  // project.index.json — full canonical record.
  writeFileSync(
    resolve(STATE_DIR, "project.index.json"),
    JSON.stringify({ version: EOS.version, generated_at: EOS.createdAt, count: c.tspecs.length, tspecs: c.tspecs }, null, 2) + "\n",
    "utf8",
  );

  // project.graph.yaml — node/edge dependency graph.
  writeYaml(resolve(STATE_DIR, "project.graph.yaml"), "Project execution graph", {
    nodes: c.tspecs.map((t) => ({ id: t.id, owner: t.owner, wave: t.wave, critical_path: t.critical_path })),
    edges: c.tspecs.flatMap((t) => t.depends_on.map((d) => ({ from: d, to: t.id }))),
  });

  // project.dependencies.yaml
  writeYaml(resolve(STATE_DIR, "project.dependencies.yaml"), "Dependency adjacency", {
    dependencies: c.tspecs.map((t) => ({ id: t.id, depends_on: t.depends_on, blocks: t.blocks })),
  });

  // project.waves.yaml
  writeYaml(resolve(STATE_DIR, "project.waves.yaml"), "Execution waves (max parallelism per wave)", {
    waves: waves.map((w) => ({ wave: w, parallel_group: `wave-${w}`, tspecs: byWave(w).map((t) => t.id) })),
  });

  // project.execution.yaml
  writeYaml(resolve(STATE_DIR, "project.execution.yaml"), "Execution DAG + topological order", {
    topological_order: c.order,
    waves: waves.map((w) => ({ wave: w, tspecs: byWave(w).map((t) => t.id) })),
    critical_path: criticalIds,
  });

  // project.state.yaml
  writeYaml(resolve(STATE_DIR, "project.state.yaml"), "Per-TSPEC lifecycle state", {
    legal_states: HAPPY_PATH,
    states: c.tspecs.map((t) => ({ id: t.id, state: t.state })),
  });

  // project.ownership.yaml
  writeYaml(resolve(STATE_DIR, "project.ownership.yaml"), "Ownership (exactly one role each)", {
    summary: { ROLE_ARCHITECT: architects.length, ROLE_IMPLEMENTER: implementers.length },
    ownership: c.tspecs.map((t) => ({ id: t.id, owner: t.owner, package: t.package })),
  });

  // project.review.yaml
  writeYaml(resolve(STATE_DIR, "project.review.yaml"), "Review chain", {
    gate: ["TESTS_COMPLETE", "REVIEW_PENDING", "ARCHITECT_REVIEW", "APPROVED"],
    reviews: c.tspecs.map((t) => ({ id: t.id, reviewers: t.reviewers })),
  });

  // project.versions.yaml
  writeYaml(resolve(STATE_DIR, "project.versions.yaml"), "Versions", {
    repository_version: EOS.version,
    rir_version: "1.0.0",
    requirement_ir_version: "1.0.0",
    ontology_version: "1.0.0",
    tspecs: c.tspecs.map((t) => ({ id: t.id, version: t.version })),
  });

  // project.timeline.yaml — deterministic wave schedule by cumulative effort.
  let cumulative = 0;
  writeYaml(resolve(STATE_DIR, "project.timeline.yaml"), "Wave timeline (effort units)", {
    timeline: waves.map((w) => {
      const effort = byWave(w).reduce((s, t) => s + t.estimated_effort, 0);
      const start = cumulative;
      cumulative += effort;
      return { wave: w, effort, start_unit: start, end_unit: cumulative, tspecs: byWave(w).length };
    }),
    total_effort: totalEffort,
  });

  // project.metrics.yaml
  writeYaml(resolve(STATE_DIR, "project.metrics.yaml"), "Project metrics", {
    total_tspecs: c.tspecs.length,
    by_owner: { ROLE_ARCHITECT: architects.length, ROLE_IMPLEMENTER: implementers.length },
    by_wave: waves.map((w) => ({ wave: w, count: byWave(w).length })),
    total_effort: totalEffort,
    critical_path_length: criticalIds.length,
    coverage_target: EOS.coverageTarget,
    work_orders: { required: specRequired.length, written: specWritten.length, spec_coverage_pct: specCoveragePct },
  });

  // project.risks.yaml
  const high = c.tspecs.filter((t) => t.risk === "HIGH");
  writeYaml(resolve(STATE_DIR, "project.risks.yaml"), "Risk register", {
    high_risk: high.map((t) => ({ id: t.id, title: t.title, risk: t.risk, critical_path: t.critical_path })),
    risk_score: Number((high.length / Math.max(1, c.tspecs.length)).toFixed(3)),
  });

  // project.lock.yaml — architecture lock.
  writeYaml(resolve(STATE_DIR, "project.lock.yaml"), "Architecture lock (protected artifacts)", {
    protected: [
      "Repository IR", "Requirement IR", "Ontology", "Compiler pipeline", "Builder contracts",
      "Decision documents", "Capability definitions", "Execution closure", "Coverage rules",
      "Consistency rules", "Graph semantics",
    ],
    rule: "Any change to a protected artifact requires a ROLE_ARCHITECT TSPEC + ADR; implementation is blocked until merged.",
    owning_tspecs: architects.map((t) => ({ id: t.id, protects: t.title })),
  });

  // project.health.yaml — computed from synced state (eos/completed.json).
  const complete = completeSet.size;
  const criticalDone = c.tspecs.filter((t) => t.critical_path && completeSet.has(t.id)).length;
  writeYaml(resolve(STATE_DIR, "project.health.yaml"), "Repository health", {
    completion_pct: Number(((complete / c.tspecs.length) * 100).toFixed(1)),
    completed_tspecs: complete,
    total_tspecs: c.tspecs.length,
    coverage_target_pct: EOS.coverageTarget * 100,
    work_orders_written: specWritten.length,
    work_orders_required: specRequired.length,
    work_order_coverage_pct: specCoveragePct,
    ready_to_implement: ready.length,
    ready_ids: ready.map((t) => t.id),
    blocked_tspecs: blocked.length,
    critical_path_progress_pct: Number(((criticalDone / Math.max(1, criticalIds.length)) * 100).toFixed(1)),
    architecture_stability: c.errors.length === 0 ? "STABLE" : "DRIFT",
    compiler_health: c.errors.length === 0 ? "GREEN" : "RED",
    risk_score: Number((high.length / Math.max(1, c.tspecs.length)).toFixed(3)),
    status: c.errors.length === 0 ? "GREEN" : "RED",
  });
}

// --- main ------------------------------------------------------------------
const result = compile(DATASET);
for (const w of result.warnings) process.stdout.write(`WARN  ${w}\n`);
for (const e of result.errors) process.stderr.write(`ERROR ${e}\n`);
if (result.errors.length > 0) {
  process.stderr.write(`\nProject Compiler FAILED with ${result.errors.length} error(s).\n`);
  process.exit(1);
}
emit(result);
const waves = new Set(result.tspecs.map((t) => t.wave)).size;
const reqSpecs = result.tspecs.filter((t) => t.spec_required);
const writtenSpecs = reqSpecs.filter((t) => t.spec_status === "WRITTEN");
process.stdout.write(
  `Project Compiler OK — ${result.tspecs.length} TSPECs, ${waves} waves, ` +
    `${result.tspecs.filter((t) => t.critical_path).length} on critical path.\n` +
    `Work orders: ${writtenSpecs.length}/${reqSpecs.length} written ` +
    `(${reqSpecs.length - writtenSpecs.length} implementer TSPECs not yet ready).\n` +
    `Emitted eos/tspecs/*.yaml and eos/state/project.*\n`,
);
